window.t = function(key) {
  const lang = window.SJP_LANG || 'es';
  return (window.SJP_I18N[lang] && window.SJP_I18N[lang][key]) || window.SJP_I18N.es[key] || key;
};

window.setLang = function(lang) {
  window.SJP_LANG = lang === 'en' ? 'en' : 'es';
  localStorage.setItem('sjp-lang', window.SJP_LANG);
  window.dispatchEvent(new Event('sjp-lang-change'));
};

