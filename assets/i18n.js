/* Apply admin text overrides (after SJP_I18N is defined) */
(function applyTextOverrides(){
  try {
    const raw = localStorage.getItem('sjp-admin-texts');
    if (!raw) return;
    const o = JSON.parse(raw);
    ['es','en'].forEach(l => {
      if (o[l]) Object.keys(o[l]).forEach(k => { window.SJP_I18N[l][k] = o[l][k]; });
    });
  } catch(e){}
})();
